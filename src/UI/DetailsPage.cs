        void UpdateWants()
        {
            bool gui = false, io = false;
            foreach (var c in _list.Columns) if (c.Visible) { if (c.Id == "userobj" || c.Id == "gdiobj") gui = true; if (c.Id == "iopri") io = true; }
            WantsGui = gui; WantsIoPriority = io;
            Data.WantGuiResources = gui && Visible; Data.WantIoPriority = io && Visible;
        }

        public override void DataUpdated() { if (Visible) Rebuild(); }
        public override void StaticUpdated() { if (Visible) Rebuild(); }

        string UserName(ProcInfo p)
        {
            var s = p.Static;
            if (s == null) return "";
            if (s.UserName == null) return p.Pid == 0 || p.Pid == 4 ? "SYSTEM" : "";
            return Main.ShowFullAccountName && !string.IsNullOrEmpty(s.UserDomain) ? s.UserDomain + "\\" + s.UserName : s.UserName;
        }

        string StatusText(ProcInfo p)
        {
            if (Data.Windows.TryGetValue(p.Pid, out var wl)) foreach (var w in wl) if (w.Hung) return Strings.NotResponding;
            return p.Cur.Suspended && Main.ShowSuspendedStatus ? Strings.Suspended : p.Cur.Suspended ? "" : Strings.Running;
        }

        static string Description(ProcInfo p)
        {
            if (p.Pid == 0) return "Percentage of time the processor is idle";
            if (p.Pid == 4) return "NT Kernel & System";
            return p.Static?.Description ?? "";
        }

        static string VirtText(ProcInfo p)
        {
            var s = p.Static;
            if (s == null || s.Virtualization < 0) return "";
            return s.Virtualization == 0 ? "Not allowed" : s.Virtualization == 2 ? Strings.Enabled : Strings.Disabled;
        }

        public static string PriorityName(int basePri)
        {
            if (basePri >= 24) return "Realtime";
            if (basePri >= 13) return "High";
            if (basePri >= 10) return "Above normal";
            if (basePri >= 8) return "Normal";
            if (basePri >= 6) return "Below normal";
            if (basePri >= 1) return "Low";
            return "N/A";
        }

        static string IoPriorityName(int v)
        {
            switch (v) { case 0: return "Very low"; case 1: return "Low"; case 2: return "Normal"; case 3: return "High"; case 4: return "Critical"; }
            return "";
        }

        // ================================================================== rows
        void Rebuild()
        {
            var procs = Data.Procs;
            var rows = new List<ListRow>(procs.Count);
            var alive = new HashSet<string>();
            foreach (var p in procs)
            {
                var key = p.Key;
                alive.Add(key);
                if (!_rows.TryGetValue(key, out var r)) { r = new ListRow { Key = key, Tag = p }; _rows[key] = r; }
                r.Icon = p.Static?.IconSmall ?? IntPtr.Zero;
                r.Dim = p.Cur.Suspended;
                rows.Add(r);
            }
            if (_rows.Count > alive.Count + 64)
            {
                var dead = new List<string>();
                foreach (var k in _rows.Keys) if (!alive.Contains(k)) dead.Add(k);
                foreach (var k in dead) _rows.Remove(k);
            }
            var col = _cols.Find(c => c.C.Id == _list.SortColumn);
            bool desc = _list.SortDescending;
            rows.Sort((a, b) =>
            {
                var x = (ProcInfo)a.Tag; var y = (ProcInfo)b.Tag;
                int r = 0;
                if (col != null)
                {
                    if (col.Num != null) r = col.Num(x).CompareTo(col.Num(y));
                    else r = string.Compare(col.Text(x), col.Text(y), StringComparison.CurrentCultureIgnoreCase);
                }
                if (desc) r = -r;
                if (r == 0) r = string.Compare(x.Name, y.Name, StringComparison.CurrentCultureIgnoreCase);
                if (r == 0) r = x.Pid.CompareTo(y.Pid);
                return r;
            });
            _list.SetRoots(rows);
        }

        List<ProcInfo> Selected
        {
            get { var l = new List<ProcInfo>(); foreach (var r in _list.SelectedRows) l.Add((ProcInfo)r.Tag); return l; }
        }

        public void SelectPid(int pid)
        {
            Rebuild();
            if (Data.ProcByPid.TryGetValue(pid, out var p)) _list.SelectKey(p.Key);
        }

        // ================================================================== commands
        public override void UpdateCommandBar(CommandBar bar)
        {
            bar.ButtonText = Strings.EndTaskButton;
            bar.ButtonEnabled = _list.SelectedRows.Count > 0;
            bar.LinkText = null; bar.LinkIcon = null;
        }

        public override void CommandButton() => EndTask();

        void EndTask() { var sel = Selected; if (sel.Count > 0) Actions.EndProcess(Main, sel); }

        void OnRowMenu(ListRow row, Point screen)
        {
            if (row == null) return;
            var sel = Selected;
            if (sel.Count == 0) return;
            var p = sel[0];
            bool single = sel.Count == 1;
            int cls = single ? Actions.GetPriorityClass(p) : 0;
            var pri = new List<MenuItem>();
            int[] classes = { 0x100, 0x80, 0x8000, 0x20, 0x4000, 0x40 };
            string[] names = { "&Realtime", "&High", "&Above normal", "&Normal", "&Below normal", "&Low" };
            for (int i = 0; i < classes.Length; i++)
            {
                int c = classes[i];
                pri.Add(MenuItem.RadioItem(names[i], () => cls == c, () => Actions.SetPriority(Main, p, c)));
            }
            bool hasServices = Data.ServicesByPid.ContainsKey(p.Pid);
            var items = new List<MenuItem>
            {
                // Taskmgr menu #30200 (CPU Context)
                new MenuItem("&End task", EndTask) { Id = 30400 },
                new MenuItem("End process &tree", () => Actions.EndProcessTree(Main, Selected)) { Id = 30401 },
                MenuItem.Sep(),
                new MenuItem("Set &priority", null, () => single) { Sub = pri, Id = 30494 },
                new MenuItem("Set a&ffinity", () => AffinityDialog.ShowAsync(Main, p), () => single && p.Pid > 4) { Id = 30410 },
                MenuItem.Sep(),
                new MenuItem("&Analyze wait chain", () => WaitChainDialog.ShowAsync(Main, p), () => single && p.Pid > 4) { Id = 30411 },
            };
            if (Actions.HasDebugger) items.Add(new MenuItem("&Debug", () => Actions.Debug(Main, p), () => single) { Id = 30452 });
            var virt = MenuItem.Check("UAC &virtualization", () => p.Static != null && p.Static.Virtualization == 2, () => Actions.ToggleVirtualization(Main, p));
            virt.Enabled = () => single && p.Static != null && p.Static.Virtualization > 0;
            items.Add(virt);
            items.Add(new MenuItem("&Create dump file", () => Actions.CreateDump(Main, p), () => single && p.Pid > 4) { Id = 30453 });
            items.Add(MenuItem.Sep());
            items.Add(new MenuItem("&Open file location", () => Actions.OpenFileLocation(Main, p.Static?.ImagePath), () => single && !string.IsNullOrEmpty(p.Static?.ImagePath)) { Id = 30455 });
            items.Add(new MenuItem("Search o&nline", () => Actions.SearchOnline(p), () => single) { Id = 30422 });
            items.Add(new MenuItem("P&roperties", () => Actions.Properties(Main, p.Static?.ImagePath), () => single && !string.IsNullOrEmpty(p.Static?.ImagePath)) { Id = 30457 });
            items.Add(new MenuItem("Go to &service(s)", () => Main.GoToServices(p.Pid), () => single && hasServices) { Id = 30433 });
            Main.ShowContextMenu(items, screen);
        }

        void OnHeaderMenu(ListColumn col, Point screen)
        {
            // Taskmgr menu #30201 (Header Context)
            var items = new List<MenuItem>
            {
                new MenuItem("Hi&de column", () => { col.Visible = false; _list.SetRoots(new List<ListRow>(_list.Roots)); SaveSettings(); UpdateWants(); }, () => col != null && !col.Fixed),
                new MenuItem("&Select columns", () => SelectColumnsDialog.ShowAsync(Main, _list, () => { SaveSettings(); UpdateWants(); Rebuild(); })),
            };
            Main.ShowContextMenu(items, screen);
        }

        public override void LoadSettings() { LoadColumns("Details", _list); if (string.IsNullOrEmpty(_list.SortColumn)) _list.SortColumn = "name"; }
        public override void SaveSettings() => SaveColumns("Details", _list);
